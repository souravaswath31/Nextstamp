#!/usr/bin/env python3
"""Wire generated images into the site.

    python3 scripts/apply_new_images.py [--check]

Looks in public/itineraries/<itinerary-slug>.jpg and public/countries/<country-slug>.jpg.
  * An itinerary image found there becomes that itinerary's `cover_image_url` in
    data/itineraries-seed.json (replacing the generic /category-*.jpg).
  * A country image found there is added to src/lib/countryHero.ts (the country page banner).
Files that are missing are listed and left on their generic fallback, so this can be run in batches.
`--check` reports only. After a real run, load the covers with:  npx tsx prisma/update-cover-images.ts
"""
import json
import re
import struct
import sys
import unicodedata
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
PUB = ROOT / "public"
SEED = ROOT / "data" / "itineraries-seed.json"
FACTS = ROOT / "data" / "country-facts-seed.json"
HERO_TS = ROOT / "src" / "lib" / "countryHero.ts"
MAX_BYTES = 600_000


def slugify(t):
    t = unicodedata.normalize("NFKD", t)
    t = re.sub("[̀-ͯ]", "", t).lower().replace("&", " and ").replace("'", "").replace("’", "")
    return re.sub("[^a-z0-9]+", "-", t).strip("-")[:80].rstrip("-")


def jpeg_size(p):
    d = p.read_bytes()
    i = 2
    while i + 9 < len(d):
        if d[i] != 0xFF:
            i += 1
            continue
        m = d[i + 1]
        if m in (0xC0, 0xC1, 0xC2):
            h, w = struct.unpack(">HH", d[i + 5:i + 9])
            return w, h
        i += 2 + struct.unpack(">H", d[i + 2:i + 4])[0]
    return None


def problems(p):
    out = []
    if p.read_bytes()[:3] != b"\xff\xd8\xff":
        return ["not a JPEG (rename/convert it to a real .jpg)"]
    wh = jpeg_size(p)
    if wh and abs(wh[0] / wh[1] - 8 / 3) > 0.35:
        out.append(f"shape {wh[0]}x{wh[1]} is not close to 8:3 (1600x600); it will be cropped by the page")
    if wh and wh[0] < 1200:
        out.append(f"only {wh[0]}px wide (want 1600)")
    if p.stat().st_size > MAX_BYTES:
        out.append(f"{p.stat().st_size // 1000} KB is large (aim for under 400 KB)")
    return out


def main():
    check = "--check" in sys.argv
    its = json.loads(SEED.read_text())
    wired = missing = 0
    print("Itineraries")
    for it in its:
        slug = slugify(it["title"])
        f = PUB / "itineraries" / f"{slug}.jpg"
        want = f"/itineraries/{slug}.jpg"
        generic = (it.get("cover_image_url") or "").startswith("/category-")
        if f.exists():
            pr = problems(f)
            for x in pr:
                print(f"  warn  {slug}: {x}")
            if it.get("cover_image_url") != want:
                it["cover_image_url"] = want
                wired += 1
                print(f"  wire  {slug}")
        elif generic and it["countries"] and not it["countries"] == ["USA"] and it["countries"] != "USA":
            missing += 1
    # list which of the new (non-USA, round 5) itineraries still lack an image
    lacking = [slugify(i["title"]) for i in its
               if i["countries"] not in ("USA", ["USA"]) and not (PUB / "itineraries" / f"{slugify(i['title'])}.jpg").exists()
               and i["title"] in ROUND5]
    print(f"  {wired} newly wired; still without a dedicated image: {len(lacking)}")
    for s in lacking:
        print(f"    - {s}")
    if wired and not check:
        SEED.write_text(json.dumps(its, indent=2, ensure_ascii=False) + "\n")

    print("\nCountries")
    facts = json.loads(FACTS.read_text())
    heroes, lack_c = {}, []
    for c in facts:
        slug = c["country"].lower().replace(" ", "-")
        f = PUB / "countries" / f"{slug}.jpg"
        if f.exists():
            for x in problems(f):
                print(f"  warn  {slug}: {x}")
            heroes[slug] = f"/countries/{slug}.jpg"
        elif slug in ROUND5_COUNTRIES:
            lack_c.append(slug)
    print(f"  {len(heroes)} banners found; still without: {len(lack_c)}")
    for s in lack_c:
        print(f"    - {s}")
    body = ("// Banner photo per country guide, keyed by the guide's URL slug. Generated by\n"
            "// `scripts/apply_new_images.py` from the files in public/countries/ — do not edit by hand.\n"
            "// A country with no entry simply shows no banner.\n"
            "export const COUNTRY_HERO: Record<string, string> = {\n"
            + "".join(f'  "{k}": "{v}",\n' for k, v in sorted(heroes.items()))
            + "};\n\nexport function countryHeroFor(slug: string): string | null {\n  return COUNTRY_HERO[slug] ?? null;\n}\n")
    if not check:
        HERO_TS.write_text(body)
        print("\nWrote data/itineraries-seed.json and src/lib/countryHero.ts" if wired or heroes else "\nNothing to wire yet.")
    return 0


ROUND5 = {
    "Paris + Loire Valley Châteaux, France", "Provence + the French Riviera, France",
    "Rome, Florence + Venice by Rail, Italy", "Naples, Pompeii, Capri + the Amalfi Coast, Italy",
    "Madrid, Toledo, Seville + Granada, Spain", "Barcelona, Valencia + Mallorca, Spain",
    "Lisbon, Sintra, Porto + Douro Valley by Train, Portugal", "Alentejo + Algarve by Train, Portugal",
    "Athens, Delphi + Nafplio, Greece", "Paros, Naxos + Santorini, Greece",
    "London, Bath + Oxford, England", "Edinburgh, Scottish Highlands + Isle of Skye, Scotland",
    "Vancouver, Whistler + Banff to Jasper, Canada", "Toronto, Niagara, Montréal + Québec City, Canada",
    "Sydney, Melbourne + the Great Ocean Road, Australia",
    "Red Centre Way: Alice Springs, Kings Canyon + Uluru, Australia",
    "Cape Town, Winelands + Garden Route, South Africa", "Johannesburg + Kruger National Park, South Africa",
    "Seoul, DMZ, Gyeongju + Busan, South Korea", "Jeju Island + Jeonju, South Korea",
}
ROUND5_COUNTRIES = {"france", "italy", "spain", "portugal", "greece", "uk", "canada", "australia", "south-korea", "south-africa"}

if __name__ == "__main__":
    sys.exit(main())
